import { writeFile } from "node:fs/promises";
import { Buffer } from "node:buffer";
import { getNotebookCatalog, loadNotebookConfig } from "../src/notebooks/registry.js";

const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const inserts = [];
const originalSlugs = new Set(["internet-browser", "http-protocol", "prisma-orm"]);
for (const item of getNotebookCatalog().filter(({ slug }) => originalSlugs.has(slug))) {
  const config = await loadNotebookConfig(item.slug);
  inserts.push(`insert into public.guided_notebooks (slug, description, node_id, pending_node_slug, config)
select ${quote(item.slug)}, ${quote(item.description)}, n.id,
  case when n.id is null then ${quote(item.slug)} else null end,
  convert_from(decode(${quote(Buffer.from(JSON.stringify(config), "utf8").toString("base64"))}, 'base64'), 'UTF8')::jsonb
from (select 1) seed left join public.nodes n on n.slug = ${quote(item.slug)}
on conflict (slug) do nothing;`);
}

await writeFile(
  new URL("../supabase/migrations/0010_seed_guided_notebooks.sql", import.meta.url),
  `-- Generated by node scripts/generate-notebook-migration.js from the original notebook configs.\n${inserts.join("\n\n")}\n`,
);

const webFoundations = getNotebookCatalog().find(
  ({ slug }) => slug === "web-foundations",
);
const webFoundationsConfig = await loadNotebookConfig(webFoundations.slug);
const webFoundationsInsert = `insert into public.guided_notebooks (slug, description, node_id, pending_node_slug, config)
select ${quote(webFoundations.slug)}, ${quote(webFoundations.description)}, n.id, null,
  convert_from(decode(${quote(Buffer.from(JSON.stringify(webFoundationsConfig), "utf8").toString("base64"))}, 'base64'), 'UTF8')::jsonb
from public.nodes n where n.slug = 'web-foundations'
on conflict (slug) do nothing;`;

