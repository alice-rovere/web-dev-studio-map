import { writeFile } from "node:fs/promises";
import { Buffer } from "node:buffer";
import { getNotebookCatalog, loadNotebookConfig } from "../src/notebooks/registry.js";

const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const encode = (value) =>
  quote(Buffer.from(JSON.stringify(value), "utf8").toString("base64"));
const entries = getNotebookCatalog().filter(({ slug }) =>
  ["web-professions", "web-infrastructure"].includes(slug),
);
const nodes = [
  {
    slug: "web-professions",
    label: "Professioni nel Web",
    description:
      "Ruoli e competenze dei team che progettano, sviluppano, verificano e mantengono prodotti Web.",
    category: "tools",
    studyUrls: [
      {
        label: "MDN: Getting started with the Web",
        url: "https://developer.mozilla.org/docs/Learn/Getting_started_with_the_web",
      },
    ],
  },
  {
    slug: "web-infrastructure",
    label: "Server e infrastruttura Web",
    description:
      "Server, data center, server farm, reti, bilanciamento e modelli cloud che mantengono disponibili i servizi Web.",
    category: "devops",
    studyUrls: [
      {
        label: "MDN: How the Web Works",
        url: "https://developer.mozilla.org/docs/Learn/Common_questions/Web_mechanisms/How_does_the_Internet_work",
      },
      {
        label: "Google Cloud: Cloud Computing",
        url: "https://cloud.google.com/learn/what-is-cloud-computing",
      },
    ],
  },
];

const nodeInserts = nodes
  .map(
    ({ slug, label, description, studyUrls, category }) => `insert into public.nodes (slug, label, description, best_practices, naming_conventions, study_urls)
values (
  ${quote(slug)},
  ${quote(label)},
  ${quote(description)},
  array[]::text[],
  array[]::text[],
  ${quote(JSON.stringify(studyUrls))}::jsonb
)
on conflict (slug) do nothing;

insert into public.node_categories (node_id, category, is_primary)
select id, ${quote(category)}, true from public.nodes where slug = ${quote(slug)}
on conflict (node_id, category) do nothing;`,
  )
  .join("\n\n");

const sectionInserts = [
  {
    slug: "web-professions",
    title: "Professioni nel Web",
    text: "Frontend e backend developer costruiscono interfacce e servizi; full-stack developer lavorano su entrambi gli ambiti. Web designer e professionisti UI/UX progettano interfacce e flussi. QA verifica la qualità; DevOps e sistemisti curano rilascio, sistemi e infrastruttura. Le responsabilità possono sovrapporsi e cambiano in base al team.",
  },
  {
    slug: "web-infrastructure",
    title: "Server e infrastruttura Web",
    text: "Server indica il ruolo di un sistema che offre un servizio a un client; può essere un computer fisico, una macchina virtuale o una risorsa cloud. Il web server riceve richieste HTTP, mentre l'applicazione esegue la logica del prodotto. Data center e server farm ospitano e coordinano macchine, reti, alimentazione e raffreddamento. Bilanciamento e ridondanza aiutano a gestire carico e disponibilità; i backup servono a recuperare dati. I modelli IaaS, PaaS e serverless differiscono per quanta infrastruttura gestisce il provider.",
  },
]
  .map(
    ({ slug, title, text }) => `insert into public.node_content_sections (node_id, sort_order, title, type, payload)
select id, 0, ${quote(title)}, 'text', jsonb_build_object('text', ${quote(text)})
from public.nodes
where slug = ${quote(slug)}
  and not exists (
    select 1 from public.node_content_sections
    where node_id = public.nodes.id and title = ${quote(title)}
  );`,
  )
  .join("\n\n");

const notebookInserts = [];
for (const entry of entries) {
  const config = await loadNotebookConfig(entry.slug);
  notebookInserts.push(`insert into public.guided_notebooks (slug, description, node_id, pending_node_slug, config)
select ${quote(entry.slug)}, ${quote(entry.description)}, n.id,
  case when n.id is null then ${quote(entry.slug)} else null end,
  convert_from(decode(${encode(config)}, 'base64'), 'UTF8')::jsonb
from (select 1) seed left join public.nodes n on n.slug = ${quote(entry.slug)}
on conflict (slug) do nothing;`);
}

await writeFile(
  new URL("../supabase/migrations/0017_seed_web_foundations.sql", import.meta.url),
  `-- Generated by node scripts/generate-notebook-migration.js from the two independent Web learning paths.
${nodeInserts}

${sectionInserts}

${notebookInserts.join("\n\n")}
`,
);
